#!/usr/bin/env python3
"""Build a dsd_font_t from nds-bootstrap's in-game menu font.

The menu's font is 256 glyphs of 8x8 1bpp: ascii.lz77 (glyphs 0-127) plus one
language file for the upper half (glyphs 128-255). Which Unicode character each
glyph draws is in nds-bootstrap's retail/arm9/source/text.cpp (mapAscii and the
extended maps). Both come from the nds-bootstrap checkout at build time, so the
font isn't copied into this repo.

usage: fontgen.py <nds-bootstrap dir> <language> <name> <out.c>
  language: extended_latin, cyrillic, greek, vietnamese, japanese, ...
"""
import re
import sys

MAPS = {
    "arabic": "mapArabic", "chinese": "mapChinese", "cyrillic": "mapCyrillic",
    "extended_latin": "mapExtendedLatin", "greek": "mapGreek", "hangul": "mapHangul",
    "hebrew": "mapHebrew", "japanese": "mapJapanese", "vietnamese": "mapVietnamese",
}


def lz10_decode(data):
    """GBA/DS BIOS LZ77 (type 0x10)."""
    if data[0] != 0x10:
        raise ValueError("not LZ10")
    size = data[1] | data[2] << 8 | data[3] << 16
    out = bytearray()
    i = 4
    while len(out) < size:
        flags = data[i]
        i += 1
        for bit in range(8):
            if len(out) >= size:
                break
            if flags & (0x80 >> bit):
                b0, b1 = data[i], data[i + 1]
                i += 2
                length = (b0 >> 4) + 3
                disp = ((b0 & 0xF) << 8 | b1) + 1
                for _ in range(length):
                    out.append(out[-disp])
            else:
                out.append(data[i])
                i += 1
    return bytes(out[:size])


def cpp_map(source, name):
    """The char16_t values of `constexpr char16_t <name>[] = u"..." u"...";`."""
    m = re.search(r"constexpr char16_t " + name + r"\[\]\s*=\s*(.*?\");", source, re.S)
    if not m:
        raise ValueError(name + " not found")
    out = []
    for lit in re.findall(r'u"((?:[^"\\]|\\.)*)"', m.group(1)):
        i = 0
        while i < len(lit):
            c = lit[i]
            if c == "\\":
                n = lit[i + 1]
                if n == "x":
                    j = i + 2
                    while j < len(lit) and lit[j] in "0123456789abcdefABCDEF":
                        j += 1
                    out.append(int(lit[i + 2:j], 16))
                    i = j
                    continue
                out.append(ord({"n": "\n", "t": "\t", "0": "\0"}.get(n, n)))
                i += 2
                continue
            out.append(ord(c))
            i += 1
    return out


def main():
    root, lang, name, out_path = sys.argv[1:5]
    fonts = root + "/retail/nitrofiles/fonts/"
    lower = lz10_decode(open(fonts + "ascii.lz77", "rb").read())
    upper = lz10_decode(open(fonts + lang + ".lz77", "rb").read())
    glyphs = (lower + bytes(1024))[:1024] + (upper + bytes(1024))[:1024]

    source = open(root + "/retail/arm9/source/text.cpp", encoding="utf-8").read()
    lo = (cpp_map(source, "mapAscii") + [0] * 128)[:128]
    hi = (cpp_map(source, MAPS[lang]) + [0] * 128)[:128]
    # The maps pad unused upper slots with spaces; ASCII already has the space.
    hi = [0 if c in (0x20, 0x3000) else c for c in hi]
    cps = lo + hi

    with open(out_path, "w") as f:
        f.write("/* Generated by fontgen.py from nds-bootstrap's in-game menu font (GPL-3.0). */\n")
        f.write('#include "dsd.h"\n\n')
        f.write("static const uint8_t glyphs[2048] = {\n")
        for i in range(0, 2048, 16):
            f.write("  " + ", ".join("0x%02x" % b for b in glyphs[i:i + 16]) + ",\n")
        f.write("};\n\nstatic const uint16_t codepoints[256] = {\n")
        for i in range(0, 256, 16):
            f.write("  " + ", ".join("0x%04x" % c for c in cps[i:i + 16]) + ",\n")
        f.write("};\n\nconst dsd_font_t %s = { glyphs, codepoints };\n" % name)


if __name__ == "__main__":
    main()
