#!/usr/bin/env python3
"""Generic input script for the M1 display survey (melonds-headless --script).

Keys: A=1 B=2 SELECT=4 START=8 RIGHT=16 LEFT=32 UP=64 DOWN=128 R=256 L=512 X=1024 Y=2048.
Lines: "FRAME KEYMASK HOLD" or "FRAME TOUCH X Y HOLD".

Phase 1 (first 90 s): get through intros, menus and new-game prompts: START, A
and a touch tap at the screen centre in turn, one every 20 frames, plus a
"down, A" every few seconds for menus whose first entry is Continue/Options.
Phase 2 (rest): play-ish input: d-pad holds in a fixed pseudo-random order,
A/B/Y presses, touch taps at a grid of spots, a START+A every ~20 s to leave
pauses and dialogs. Deterministic (fixed seed), so every title sees the same input.
"""
import random
import sys

frames = int(sys.argv[1]) if len(sys.argv) > 1 else 54000
rng = random.Random(1234)
out = ["# generated by make_script.py: generic survey input"]
f = 60
while f < 5400:
    k = (f // 20) % 3
    if k == 0:
        out.append(f"{f} 8 4")             # START
    elif k == 1:
        out.append(f"{f} 1 4")             # A
    else:
        out.append(f"{f} TOUCH 128 96 4")  # tap the centre
    if f % 300 == 0:
        out.append(f"{f + 10} 128 4")      # DOWN, then A comes next round
    f += 20
dirs = [16, 32, 64, 128, 16 | 64, 32 | 64]
spots = [(128, 96), (64, 48), (192, 48), (64, 144), (192, 144), (128, 170), (40, 96), (216, 96)]
while f < frames:
    d = rng.choice(dirs)
    hold = rng.choice([30, 60, 90])
    out.append(f"{f} {d} {hold}")
    t = f
    while t < f + hold:
        out.append(f"{t + 5} {rng.choice([1, 1, 2, 2048, 1024])} 4")
        t += 20
    x, y = rng.choice(spots)
    out.append(f"{f + hold + 2} TOUCH {x} {y} 6")
    if (f // 1200) != ((f + hold + 20) // 1200):
        out.append(f"{f + hold + 10} 8 4")   # START
        out.append(f"{f + hold + 30} 1 4")   # A
        out.append(f"{f + hold + 50} 8 4")   # START (unpause if it paused)
        f += 60
    f += hold + 20
print("\n".join(out))
