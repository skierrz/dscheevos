#!/usr/bin/env python3
"""Generate dscheevos/launcher/tls/cacerts.c: the root CAs the launcher trusts.

retroachievements.org is behind Cloudflare, whose edge certificates chain to
one of these roots (Let's Encrypt, Google Trust Services, SSL.com, Sectigo,
DigiCert, GlobalSign). Run with the PEM files from a CA bundle, e.g.
  gen.py /etc/ssl/certs/{ISRG_Root_X1,...}.pem > cacerts.c
"""
import os
import sys

out = ['/* Generated by tools/cacerts/gen.py. Root CAs for HTTPS. */', '#include <stddef.h>', '',
       'const char dsc_cacerts[] =']
for path in sys.argv[1:]:
    pem = open(path).read().strip()
    out.append(f'  /* {os.path.basename(path)} */')
    for line in pem.splitlines():
        out.append(f'  "{line}\\n"')
out.append('  ;')
out.append('const size_t dsc_cacerts_size = sizeof(dsc_cacerts);  /* includes the NUL mbedTLS wants */')
print('\n'.join(out))
