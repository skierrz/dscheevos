#!/usr/bin/env python3
"""Generate dscheevos/launcher/tls/cacerts.c: the root CAs the launcher and
the module trust, as DER certificates one after the other (no PEM decoding
on the DS, and the module parses them in place).

retroachievements.org is behind Cloudflare, whose edge certificates chain to
one of these roots (Let's Encrypt, Google Trust Services, SSL.com, Sectigo,
DigiCert, GlobalSign). Run with the PEM files from a CA bundle, e.g.
  gen.py /etc/ssl/certs/{ISRG_Root_X1,...}.pem > cacerts.c
"""
import base64
import os
import re
import sys

out = ['/* Generated by tools/cacerts/gen.py. Root CAs for HTTPS: DER certificates,',
       ' * one after the other (dsc_parse_der_list). */', '#include <stddef.h>', '',
       'const unsigned char dsc_cacerts[] = {']
total = 0
for path in sys.argv[1:]:
    pem = open(path).read()
    for b64 in re.findall(r'-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----', pem, re.S):
        der = base64.b64decode(''.join(b64.split()))
        # a SEQUENCE with a two-byte length: what the parser expects
        assert der[0] == 0x30 and der[1] == 0x82 and len(der) == 4 + (der[2] << 8 | der[3]), path
        out.append(f'  /* {os.path.basename(path)} */')
        for i in range(0, len(der), 16):
            out.append('  ' + ''.join(f'0x{b:02x},' for b in der[i:i + 16]))
        total += len(der)
out.append('};')
out.append('const size_t dsc_cacerts_size = sizeof(dsc_cacerts);')
print('\n'.join(out))
